-- Creates the two tables the site + /admin dashboard use.
-- Safe to run again (uses IF NOT EXISTS / DROP POLICY IF EXISTS).

-- 1) Contact messages (from the contact form)
create table if not exists public.contact_submissions (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  subject text,
  message text not null,
  created_at timestamptz not null default now()
);

-- 2) App downloads (each tap on "Download APK" in the website popup)
create table if not exists public.app_downloads (
  id bigint generated by default as identity primary key,
  platform text,
  device text,
  user_agent text,
  referrer text,
  version text,
  created_at timestamptz not null default now()
);

-- Row Level Security: allow anonymous inserts (form + download tracker)
alter table public.contact_submissions enable row level security;
alter table public.app_downloads enable row level security;

drop policy if exists "anon_insert_contact" on public.contact_submissions;
create policy "anon_insert_contact" on public.contact_submissions
  for insert with check (true);

drop policy if exists "anon_select_contact" on public.contact_submissions;
create policy "anon_select_contact" on public.contact_submissions
  for select using (true);

drop policy if exists "anon_insert_downloads" on public.app_downloads;
create policy "anon_insert_downloads" on public.app_downloads
  for insert with check (true);

drop policy if exists "anon_select_downloads" on public.app_downloads;
create policy "anon_select_downloads" on public.app_downloads
  for select using (true);